import assert from 'node:assert/strict';
import {ColorSchemeController, resolveColorScheme, COLOR_SCHEME_KEY} from '../web/color-scheme.js';
const schemes=[{id:'light',base:'light'},{id:'dark',base:'dark'},{id:'mod:ocean:night',base:'dark'}];
const attributes={},values=new Map(),handlers=new Map();let requests=0;
globalThis.location={search:''};globalThis.document={getElementById:()=>null};
const storage={getItem:key=>values.get(key),setItem:(key,value)=>values.set(key,value)};
const root={setAttribute:(key,value)=>attributes[key]=value};
const events={addEventListener:(key,fn)=>handlers.set(key,fn),removeEventListener:key=>handlers.delete(key)};
const fetcher=async()=>({ok:true,json:async()=>({schemes:++requests<2?schemes:schemes.slice(0,2)})});
const controller=new ColorSchemeController({root,storage,events,fetcher});
await controller.refresh();assert.equal(attributes['data-color-scheme'],'light');
controller.apply({id:'mod:ocean:night'});assert.equal(attributes['data-color-mode'],'dark');
assert.equal(JSON.parse(values.get(COLOR_SCHEME_KEY)).id,'mod:ocean:night');
await controller.refresh();assert.equal(attributes['data-color-scheme'],'dark','Disabling a selected mod restores its base');
values.set(COLOR_SCHEME_KEY,JSON.stringify({id:'light',base:'light'}));handlers.get('storage')({key:COLOR_SCHEME_KEY});assert.equal(attributes['data-color-mode'],'light');
assert.equal(resolveColorScheme(schemes,{id:'missing',base:'dark'}).id,'dark');
values.set(COLOR_SCHEME_KEY,'invalid');controller.apply(controller.read());assert.equal(attributes['data-color-scheme'],'light');
let updates=0;const dispose=controller.subscribe(()=>updates++);controller.apply({id:'dark'});dispose();controller.apply({id:'light'});assert.equal(updates,1);
controller.storage={getItem(){throw Error('restricted');},setItem(){throw Error('restricted');}};controller.apply({id:'dark'});assert.equal(attributes['data-color-scheme'],'dark');
controller.dispose();assert.equal(handlers.size,0);
console.log('Palette persistence, cross-tab changes, disabled-mod fallback, storage recovery and disposal PASS');
