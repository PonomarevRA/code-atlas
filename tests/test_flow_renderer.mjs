/** Реальный GraphView с минимальным SVG DOM: карточки, направления, overlays и смена renderer. */
import assert from 'node:assert/strict';
import {GraphView} from '../web/graph.js';
import {displayProvider} from '../web/display-providers.js';
import {selectInCurrentView} from '../web/selection-controller.js';
import {Svg} from './svg_fixture.mjs';
globalThis.document={createElementNS:(_,tag)=>new Svg(tag)};
globalThis.ResizeObserver=class{observe(){}};
const svg=new Svg('svg'),viewport=new Svg('g');viewport.setAttribute('id','viewport');svg.append(viewport);
const selections=[],groups=[];const view=new GraphView(svg,id=>selections.push(id),id=>groups.push(id));
view.colorProjects=[{id:'p',label:'Project'}];
const nodes=[{id:'a',label:'Alpha',codeProjectId:'p',changedFile:true},{id:'b',label:'Beta',codeProjectId:'p'},{id:'alone',label:'Isolate'}];
const edges=[{source:'a',target:'b',relation:'calls'},{source:'a',target:'b',relation:'references'},{source:'b',target:'a',relation:'calls'},{source:'a',target:'a',relation:'self'}];
const before=JSON.stringify({nodes,edges});
assert.equal(displayProvider('unknown').id,'topology');
view.setDisplayProvider('flow');view.render(nodes,edges,null);
assert.equal(view.nodeElements.size,3);assert.equal(viewport.querySelectorAll('.flow-card').length,3);
assert.equal(viewport.querySelectorAll('.graph-node').length,0);
const paths=viewport.querySelectorAll('.flow-edge');assert.equal(paths.length,edges.length);
for(const path of paths){
 const source=view.positions.get(path.attributes['data-source']),target=view.positions.get(path.attributes['data-target']);
 const values=path.attributes.d.match(/-?\d+(?:\.\d+)?(?:e[+-]?\d+)?/gi).map(Number);
 assert.deepEqual(values.slice(0,2),[source.x+source.width/2,source.y]);assert.deepEqual(values.slice(-2),[target.x-target.width/2,target.y]);
 assert.equal(path.attributes.stroke,source.color);
 assert.equal(path.attributes['data-edge-kind'],source.id===target.id?'self':'back');
 const marker=viewport.querySelector(path.attributes['marker-end'].slice(4,-1));assert.ok(marker);assert.equal(marker.children[0].attributes.fill,source.color);
 const bounds=view.geometryBounds();
 for(let i=0;i<values.length;i+=2){assert.ok(values[i]>=bounds.minX&&values[i]<=bounds.maxX);assert.ok(values[i+1]>=bounds.minY&&values[i+1]<=bounds.maxY);}
}
const a=view.nodeElements.get('a').group;
assert.equal(a.querySelector('.flow-port-in').attributes.cx,-view.positions.get('a').width/2);
assert.equal(a.querySelector('.flow-port-out').attributes.cx,view.positions.get('a').width/2);
assert.equal(a.querySelector('.change-ring').tag,'rect');
assert.ok(a.querySelector('.flow-card-note').textContent.includes('Цикл'));
assert.deepEqual(a.querySelectorAll('.flow-port-label').map(e=>e.textContent),['IN 2','OUT 3']);
view.setSearchMatches(['a']);assert.equal(a.querySelector('.regex-ring').tag,'rect');
view.camera={x:70,y:90,scale:.75};const stableCamera={...view.camera},stablePositions=JSON.stringify([...view.positions]),stableChildren=[...viewport.children];
assert.equal(selectInCurrentView(view,'a'),true);assert.equal(a.querySelector('.selection-ring').tag,'rect');
assert.equal(a.attributes['aria-pressed'],true);assert.deepEqual(view.camera,stableCamera);assert.equal(JSON.stringify([...view.positions]),stablePositions);
for(let i=0;i<stableChildren.length;i++)assert.equal(viewport.children[i],stableChildren[i]);
a.listeners.click();assert.deepEqual(selections,['a']);
const signatures=()=>viewport.querySelectorAll('.flow-edge').map(p=>[p.children[0].textContent,p.attributes.d]).sort((a,b)=>JSON.stringify(a).localeCompare(JSON.stringify(b)));
const originalPaths=signatures();view.render([...nodes].reverse(),[...edges].reverse(),null);assert.deepEqual(signatures(),originalPaths);
view.renderIngress([{id:'synthetic',kind:'http',label:'GET /a',targets:['a']}],()=>{});
assert.equal(view.nodeElements.size,3);assert.equal(view.positions.has('synthetic'),false);
const ingressPath=viewport.querySelector('.ingress-edge');
const ingressMarker=viewport.querySelector(ingressPath.attributes['marker-end'].slice(4,-1));
assert.equal(ingressMarker.attributes.refX,6,'Arrow tip must meet the IN port');
assert.ok(ingressPath.attributes.d.endsWith(`${view.positions.get('a').x-view.positions.get('a').width/2} ${view.positions.get('a').y}`));
assert.equal(JSON.stringify({nodes,edges}),before);
view.renderOverview([{id:'g1',label:'Group1',nodeCount:3,changedNodeCount:2},{id:'g2',label:'Group2',nodeCount:1}], [{source:'g1',target:'g2',weight:2.5}],null);
assert.equal(view.communityElements.size,2);assert.equal(view.nodeElements.size,0);
const group=view.communityElements.get('g1').group;
assert.deepEqual(group.querySelectorAll('.flow-port-label').map(e=>e.textContent),['IN 0','OUT 2.5']);
assert.equal(view.setSearchMatches(['a','b'],new Map([['g1',2]])),2);
assert.equal(group.querySelector('.regex-ring').tag,'rect');assert.equal(group.querySelector('.change-ring').tag,'rect');
group.listeners.click();assert.deepEqual(groups,['g1']);
view.setDisplayProvider('topology');view.render(nodes,edges,null);
assert.equal(viewport.querySelectorAll('.flow-card').length,0);assert.equal(viewport.querySelectorAll('.graph-node').length,3);
console.log('Flow renderer ports, source colors, identity and provider switch PASS');
