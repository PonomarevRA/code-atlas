/** Entry preferences are bounded and project-scoped; modal lifecycle preserves native keyboard behavior. */
import assert from 'node:assert/strict';
import {createEntryMemory, normalizeEntryPreferences} from '../web/ingress-catalog-memory.js';
import {IngressCatalogPopup} from '../web/ingress-catalog-popup.js';
import {projectIngressCatalog} from '../web/ingress-catalog.js';
const values = new Map();
const storage = {getItem:key=>values.get(key),setItem:(key,value)=>values.set(key,value)};
const memory=createEntryMemory(storage);
memory.write('one',{kind:'mcp',query:'search_nodes',selectedId:'a',favorites:['a'],recent:['b','a'],scope:'favorites',page:2});
assert.equal(memory.read('one').kind,'mcp');assert.equal(memory.read('one').selectedId,'a');
assert.equal(memory.read('two').selectedId,null);
assert.equal(createEntryMemory(storage).read('one').query,'search_nodes');
const bounded=normalizeEntryPreferences({kind:'execute-shell',query:'x'.repeat(1000),page:-1,favorites:Array.from({length:90},(_,i)=>'id'+i),recent:['x','x',null],selectedId:'z'.repeat(2000)});
assert.equal(bounded.kind,null);assert.equal(bounded.query.length,500);assert.equal(bounded.favorites.length,30);assert.equal(bounded.selectedId,null);assert.deepEqual(bounded.recent,['x']);
const broken=createEntryMemory({getItem(){throw Error('blocked');},setItem(){throw Error('blocked');}});
broken.write('p',{kind:'http',selectedId:'raw'});assert.equal(broken.read('p').selectedId,'raw');
const absent=createEntryMemory(null);absent.write('p',{query:'hello'});assert.equal(absent.read('p').query,'hello');
let focused=0,opened=0,closed=0;const listeners={};
const dialog={open:false,addEventListener:(name,fn)=>listeners[name]=fn,showModal(){this.open=true;opened++;},close(){this.open=false;closed++;}};
const popup=new IngressCatalogPopup(dialog,{focus(){focused++;}});
popup.open();popup.open();assert.equal(opened,1);assert.equal(focused,1);
listeners.click({target:{}});assert.equal(closed,0);
popup.close();popup.close();assert.equal(closed,1);
popup.open();listeners.click({target:dialog});assert.equal(closed,2);
const entries=[{id:'a',kind:'http',label:'A'},{id:'b',kind:'mcp',label:'B'},{id:'c',kind:'mcp',label:'C'}];
const favorites=projectIngressCatalog(entries,{allowedIds:new Set(['b','removed'])});
assert.equal(favorites.total,1);assert.equal(favorites.entries[0].id,'b');assert.equal(favorites.counts.http,1);
assert.deepEqual(projectIngressCatalog(entries,{allowedIds:new Set(['a','b']),order:['b','a']}).entries.map(e=>e.id),['b','a']);
console.log('Entry catalogue persistence, isolation, corrupt/blocked storage, bounded lists, recent order and modal lifecycle PASS');
